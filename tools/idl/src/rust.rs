//! Generates the Rust types and their codec.

use crate::model::{Field, Payload, Schema, Type, TypeDecl, TypeKind, Variant};
use crate::naming::{MESSAGE_UNIONS, rust_field, rust_type};
use std::collections::HashSet;
use std::fmt::Write;
use std::io::Write as _;
use std::process::{Command, Stdio};

const RUNTIME: &str = include_str!("../runtime/json.rs");

const HEADER: &str = "// @generated by fluidic-ui-idl from the schema. Do not edit.";

/// The runtime without its note about being copied.
fn runtime_body() -> &'static str {
    let start = RUNTIME.find("//!").expect("the runtime's module doc");
    &RUNTIME[start..]
}

/// `write` for a message union with no messages, only its unknown case.
const ONLY_UNKNOWN: &str = "fn write(&self, _: &mut json::Writer) -> Result<(), EncodeError> {\n\
                            let Self::Unknown(name) = self;\n\
                            Err(EncodeError::unknown(name))\n}\n\n";

/// The crate's `lib.rs` and `json.rs`, formatted.
pub(crate) fn generate(schema: &Schema) -> Result<Vec<(String, String)>, String> {
    Ok(vec![
        ("lib.rs".to_string(), rustfmt(&lib(schema))?),
        (
            "json.rs".to_string(),
            rustfmt(&format!("{HEADER}\n\n{}", runtime_body()))?,
        ),
    ])
}

fn rustfmt(source: &str) -> Result<String, String> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|e| format!("cannot run rustfmt: {e}"))?;
    child
        .stdin
        .take()
        .expect("stdin")
        .write_all(source.as_bytes())
        .map_err(|e| e.to_string())?;
    let output = child.wait_with_output().map_err(|e| e.to_string())?;
    if !output.status.success() {
        return Err(format!(
            "rustfmt failed:\n{}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    String::from_utf8(output.stdout).map_err(|e| e.to_string())
}

fn docs(out: &mut String, doc: &[String]) {
    for line in doc {
        if line.is_empty() {
            out.push_str("///\n");
        } else {
            writeln!(out, "/// {line}").unwrap();
        }
    }
}

fn ty(t: &Type) -> String {
    match t {
        Type::Bool => "bool".to_string(),
        Type::U32 => "u32".to_string(),
        Type::I32 => "i32".to_string(),
        Type::U64 => "u64".to_string(),
        Type::I64 => "i64".to_string(),
        Type::F32 => "f32".to_string(),
        Type::F64 => "f64".to_string(),
        Type::String => "String".to_string(),
        Type::Version => "Version".to_string(),
        Type::List(t) => format!("Vec<{}>", ty(t)),
        Type::Map(t) => format!("BTreeMap<String, {}>", ty(t)),
        Type::Named(n) => rust_type(n),
    }
}

fn field_type(f: &Field) -> String {
    if f.optional {
        format!("Option<{}>", ty(&f.ty))
    } else {
        ty(&f.ty)
    }
}

/// Whether a value of `t` can hold a float, which rules out `Eq` and `Hash`.
fn has_float<'a>(schema: &'a Schema, t: &'a Type, seen: &mut HashSet<&'a str>) -> bool {
    match t {
        Type::F32 | Type::F64 => true,
        Type::List(t) | Type::Map(t) => has_float(schema, t, seen),
        Type::Named(n) => named_has_float(schema, n, seen),
        _ => false,
    }
}

fn named_has_float<'a>(schema: &'a Schema, name: &'a str, seen: &mut HashSet<&'a str>) -> bool {
    if !seen.insert(name) {
        return false;
    }
    let Some(decl) = schema.get(name) else {
        return false;
    };
    let fields = decl.kind.field_lists();
    fields
        .iter()
        .flat_map(|f| f.iter())
        .any(|f| has_float(schema, &f.ty, seen))
        || decl
            .kind
            .carried()
            .into_iter()
            .any(|s| named_has_float(schema, s, seen))
}

/// A type that can hold a float has no `Eq` or `Hash`.
fn derive(has_float: bool) -> &'static str {
    if has_float {
        "#[derive(Debug, Clone, PartialEq)]"
    } else {
        "#[derive(Debug, Clone, PartialEq, Eq, Hash)]"
    }
}

fn uses_map(schema: &Schema) -> bool {
    fn map(t: &Type) -> bool {
        match t {
            Type::Map(_) => true,
            Type::List(t) => map(t),
            _ => false,
        }
    }
    schema
        .types
        .iter()
        .flat_map(|t| t.kind.field_lists())
        .any(|fields| fields.iter().any(|f| map(&f.ty)))
}

fn lib(schema: &Schema) -> String {
    let mut out = String::new();
    writeln!(out, "{HEADER}\n").unwrap();
    for line in &schema.doc {
        writeln!(out, "//! {line}").unwrap();
    }
    // The schema's doc comments are its author's prose, as written.
    out.push_str(
        "\n#![allow(clippy::doc_lazy_continuation, clippy::doc_overindented_list_items)]\n",
    );
    out.push_str(
        "\n#[doc(hidden)]\npub mod json;\n\n\
         pub use json::{Canonical, DecodeError, EncodeError, Version};\n",
    );
    if uses_map(schema) {
        out.push_str("use std::collections::BTreeMap;\n");
    }
    out.push('\n');
    let c = schema.contract;
    writeln!(
        out,
        "/// The contract version this schema defines.\n\
         pub const CONTRACT: Version = Version {{ major: {}, minor: {} }};\n",
        c.major, c.minor
    )
    .unwrap();
    for (sender, name, doc) in MESSAGE_UNIONS {
        let variants = schema.message_variants(sender);
        let mut seen = HashSet::new();
        let has_float = variants
            .iter()
            .any(|v| named_has_float(schema, &v.name, &mut seen));
        docs(&mut out, &[format!("One of {doc}.")]);
        writeln!(out, "{}", derive(has_float)).unwrap();
        union(&mut out, name, &variants);
    }
    for t in &schema.types {
        declaration(&mut out, schema, t);
    }
    out
}

fn declaration(out: &mut String, schema: &Schema, t: &TypeDecl) {
    let name = rust_type(&t.name);
    docs(out, &t.doc);
    let has_float = named_has_float(schema, &t.name, &mut HashSet::new());
    writeln!(out, "{}", derive(has_float)).unwrap();
    match &t.kind {
        TypeKind::Message { fields, .. } | TypeKind::Struct { fields } => {
            writeln!(out, "pub struct {name} {{").unwrap();
            for f in fields {
                docs(out, &f.doc);
                writeln!(out, "pub {}: {},", rust_field(&f.name), field_type(f)).unwrap();
            }
            out.push_str("}\n\n");
            writeln!(out, "impl Canonical for {name} {{").unwrap();
            out.push_str("fn write(&self, w: &mut json::Writer) -> Result<(), EncodeError> {\n");
            write_fields(out, fields, |f| format!("self.{}", rust_field(&f.name)));
            out.push_str("Ok(())\n}\n\n");
            out.push_str("fn read(r: &mut json::Reader<'_>) -> Result<Self, DecodeError> {\n");
            read_fields(out, &name, fields, true);
            out.push_str("}\n}\n\n");
        }
        TypeKind::Union { variants } => union(out, &name, variants),
        TypeKind::Enum { values } => {
            writeln!(out, "pub enum {name} {{").unwrap();
            for v in values {
                docs(out, &v.doc);
                writeln!(out, "{},", rust_type(&v.name)).unwrap();
            }
            out.push_str("/// A value this side does not know, by name.\nUnknown(String),\n}\n\n");
            writeln!(out, "impl Canonical for {name} {{").unwrap();
            // The checker refuses an enum without values.
            out.push_str("fn write(&self, w: &mut json::Writer) -> Result<(), EncodeError> {\n");
            out.push_str("w.string(match self {\n");
            for v in values {
                writeln!(out, "{name}::{} => \"{}\",", rust_type(&v.name), v.name).unwrap();
            }
            writeln!(
                out,
                "{name}::Unknown(name) => return Err(EncodeError::unknown(name)),"
            )
            .unwrap();
            out.push_str("});\nOk(())\n}\n\n");
            out.push_str("fn read(r: &mut json::Reader<'_>) -> Result<Self, DecodeError> {\n");
            out.push_str("let name = String::read(r)?;\n");
            out.push_str("Ok(match name.as_str() {\n");
            for v in values {
                writeln!(out, "\"{}\" => {name}::{},", v.name, rust_type(&v.name)).unwrap();
            }
            writeln!(out, "_ => {name}::Unknown(name),\n}})").unwrap();
            out.push_str("}\n}\n\n");
        }
    }
}

/// Writes an object of `fields`, each value found by `value`.
fn write_fields(out: &mut String, fields: &[Field], value: impl Fn(&Field) -> String) {
    out.push_str("w.begin_object();\n");
    for f in fields {
        if f.optional {
            writeln!(out, "if let Some(value) = &{} {{", value(f)).unwrap();
            writeln!(out, "w.key(\"{}\");\nvalue.write(w)?;\n}}", f.name).unwrap();
        } else {
            writeln!(out, "w.key(\"{}\");\n{}.write(w)?;", f.name, value(f)).unwrap();
        }
    }
    out.push_str("w.end_object();\n");
}

/// The local a field is read into or matched as: `name_`, which no field
/// or local of the reader's can be (see `rust_field`).
fn local_name(f: &Field) -> String {
    format!("{}_", f.name)
}

/// A field bound to its local: `name: name_`, or just `self_` where the
/// field is itself `self_`.
fn bind(f: &Field) -> String {
    let (field, local) = (rust_field(&f.name), local_name(f));
    if field == local {
        local
    } else {
        format!("{field}: {local}")
    }
}

/// Reads an object of `fields`, ending with the expression `constructor { … }`,
/// or with `Ok(constructor { … })` when `ok`.
fn read_fields(out: &mut String, constructor: &str, fields: &[Field], ok: bool) {
    for f in fields {
        writeln!(out, "let mut {} = None;", local_name(f)).unwrap();
    }
    out.push_str("let mut object = r.object()?;\n");
    if fields.is_empty() {
        out.push_str("while object.next_key(r)?.is_some() {\nr.skip()?;\n}\n");
    } else {
        out.push_str("while let Some(key) = object.next_key(r)? {\nmatch key.as_str() {\n");
        for f in fields {
            writeln!(
                out,
                "\"{}\" => {} = Some(Canonical::read(r)?),",
                f.name,
                local_name(f)
            )
            .unwrap();
        }
        out.push_str("_ => r.skip()?,\n}\n}\n");
    }
    if ok {
        out.push_str("Ok(");
    }
    writeln!(out, "{constructor} {{").unwrap();
    for f in fields {
        if f.optional {
            writeln!(out, "{},", bind(f)).unwrap();
        } else {
            let (field, local) = (rust_field(&f.name), local_name(f));
            writeln!(out, "{field}: r.required({local}, \"{}\")?,", f.name).unwrap();
        }
    }
    out.push_str(if ok { "})\n" } else { "}\n" });
}

fn union(out: &mut String, name: &str, variants: &[Variant]) {
    // The types are plain, as the schema writes them: a large variant is not
    // boxed.
    writeln!(
        out,
        "#[allow(clippy::large_enum_variant)]\npub enum {name} {{"
    )
    .unwrap();
    for v in variants {
        docs(out, &v.doc);
        let variant = rust_type(&v.name);
        match &v.payload {
            Payload::None => writeln!(out, "{variant},").unwrap(),
            Payload::Struct(s) => writeln!(out, "{variant}({}),", rust_type(s)).unwrap(),
            Payload::Fields(fields) => {
                writeln!(out, "{variant} {{").unwrap();
                for f in fields {
                    docs(out, &f.doc);
                    writeln!(out, "{}: {},", rust_field(&f.name), field_type(f)).unwrap();
                }
                out.push_str("},\n");
            }
        }
    }
    out.push_str("/// A variant this side does not know, by name.\nUnknown(String),\n}\n\n");

    writeln!(out, "impl Canonical for {name} {{").unwrap();
    if variants.is_empty() {
        out.push_str(ONLY_UNKNOWN);
    } else {
        out.push_str(
            "fn write(&self, w: &mut json::Writer) -> Result<(), EncodeError> {\nmatch self {\n",
        );
        for v in variants {
            let variant = rust_type(&v.name);
            match &v.payload {
                Payload::None => {
                    writeln!(out, "{name}::{variant} => w.string(\"{}\"),", v.name).unwrap()
                }
                Payload::Struct(_) => {
                    writeln!(out, "{name}::{variant}(value) => {{").unwrap();
                    writeln!(
                        out,
                        "w.begin_object();\nw.key(\"{}\");\nvalue.write(w)?;\nw.end_object();\n}}",
                        v.name
                    )
                    .unwrap();
                }
                Payload::Fields(fields) => {
                    writeln!(out, "{name}::{variant} {{").unwrap();
                    for f in fields {
                        writeln!(out, "{},", bind(f)).unwrap();
                    }
                    out.push_str("} => {\n");
                    writeln!(out, "w.begin_object();\nw.key(\"{}\");", v.name).unwrap();
                    write_fields(out, fields, local_name);
                    out.push_str("w.end_object();\n}\n");
                }
            }
        }
        writeln!(
            out,
            "{name}::Unknown(name) => return Err(EncodeError::unknown(name)),"
        )
        .unwrap();
        out.push_str("}\nOk(())\n}\n\n");
    }

    out.push_str("fn read(r: &mut json::Reader<'_>) -> Result<Self, DecodeError> {\n");
    let bare: Vec<&Variant> = variants
        .iter()
        .filter(|v| v.payload == Payload::None)
        .collect();
    let data: Vec<&Variant> = variants
        .iter()
        .filter(|v| v.payload != Payload::None)
        .collect();
    let alternatives = |vs: &[&Variant]| {
        vs.iter()
            .map(|v| format!("\"{}\"", v.name))
            .collect::<Vec<_>>()
            .join(" | ")
    };
    if variants.is_empty() {
        out.push_str("let name = match r.tag()? {\n");
        writeln!(
            out,
            "json::Tag::Bare(name) => return Ok({name}::Unknown(name)),"
        )
        .unwrap();
        out.push_str("json::Tag::Data(name) => name,\n};\n");
        writeln!(
            out,
            "r.skip()?;\nr.end_tag()?;\nOk({name}::Unknown(name))\n}}\n}}\n"
        )
        .unwrap();
        return;
    }
    out.push_str("let name = match r.tag()? {\njson::Tag::Bare(name) => {\n");
    out.push_str("return match name.as_str() {\n");
    for v in &bare {
        writeln!(out, "\"{}\" => Ok({name}::{}),", v.name, rust_type(&v.name)).unwrap();
    }
    if !data.is_empty() {
        writeln!(
            out,
            "{} => Err(r.bare_with_data(&name)),",
            alternatives(&data)
        )
        .unwrap();
    }
    writeln!(out, "_ => Ok({name}::Unknown(name)),\n}};\n}}").unwrap();
    out.push_str("json::Tag::Data(name) => name,\n};\n");
    out.push_str("let value = match name.as_str() {\n");
    if !bare.is_empty() {
        writeln!(
            out,
            "{} => return Err(r.data_without_data(&name)),",
            alternatives(&bare)
        )
        .unwrap();
    }
    for v in &data {
        let variant = rust_type(&v.name);
        match &v.payload {
            Payload::Struct(_) => {
                writeln!(
                    out,
                    "\"{}\" => {name}::{variant}(Canonical::read(r)?),",
                    v.name
                )
                .unwrap();
            }
            Payload::Fields(fields) => {
                writeln!(out, "\"{}\" => {{", v.name).unwrap();
                read_fields(out, &format!("{name}::{variant}"), fields, false);
                out.push_str("}\n");
            }
            Payload::None => unreachable!(),
        }
    }
    writeln!(out, "_ => {{\nr.skip()?;\n{name}::Unknown(name)\n}}\n}};").unwrap();
    out.push_str("r.end_tag()?;\nOk(value)\n}\n}\n\n");
}
