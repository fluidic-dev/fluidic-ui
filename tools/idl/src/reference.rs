//! Generates the message reference, in Markdown.

use crate::model::{Direction, Field, Payload, Schema, TypeDecl, TypeKind};
use std::fmt::Write;

/// Doc lines as one table cell or sentence.
fn prose(doc: &[String]) -> String {
    // A backslash first, so that one before a `|` cannot unescape it.
    doc.join(" ").replace('\\', "\\\\").replace('|', "\\|")
}

/// `prefix` followed by the doc, as one line.
fn intro(out: &mut String, prefix: &str, doc: &[String]) {
    let doc = prose(doc);
    if doc.is_empty() {
        writeln!(out, "{prefix}\n").unwrap();
    } else {
        writeln!(out, "{prefix} {doc}\n").unwrap();
    }
}

/// A table row; an empty cell is written `| |`.
fn row(out: &mut String, cells: &[String]) {
    out.push('|');
    for cell in cells {
        if cell.is_empty() {
            out.push_str(" |");
        } else {
            write!(out, " {cell} |").unwrap();
        }
    }
    out.push('\n');
}

fn fields(out: &mut String, fields: &[Field]) {
    if fields.is_empty() {
        out.push_str("No fields.\n\n");
        return;
    }
    out.push_str("| Field | Type | Since | |\n|---|---|---|---|\n");
    for f in fields {
        let ty = if f.optional {
            format!("optional `{}`", f.ty)
        } else {
            format!("`{}`", f.ty)
        };
        row(
            out,
            &[
                format!("`{}`", f.name),
                ty,
                f.since.to_string(),
                prose(&f.doc),
            ],
        );
    }
    out.push('\n');
}

pub(crate) fn generate(schema: &Schema) -> String {
    let mut out = String::new();
    out.push_str("<!-- Generated by fluidic-ui-idl from the schema. Do not edit. -->\n\n# Message reference\n\n");
    intro(
        &mut out,
        &format!("Contract {}.", schema.contract),
        &schema.doc,
    );
    out.push_str("## Messages\n\n");
    for t in &schema.types {
        if let TypeKind::Message { from, fields: f } = &t.kind {
            writeln!(out, "### `{}`\n", t.name).unwrap();
            let sender = match from {
                Direction::App => "the app",
                Direction::Host => "the host",
                Direction::Either => "either side",
            };
            intro(
                &mut out,
                &format!("From {sender}, since {}.", t.since),
                &t.doc,
            );
            fields(&mut out, f);
        }
    }
    out.push_str("## Types\n\n");
    for t in &schema.types {
        if !matches!(t.kind, TypeKind::Message { .. }) {
            declaration(&mut out, t);
        }
    }
    while out.ends_with("\n\n") {
        out.pop();
    }
    out
}

fn declaration(out: &mut String, t: &TypeDecl) {
    writeln!(out, "### `{}` ({})\n", t.name, t.kind.keyword()).unwrap();
    intro(out, &format!("Since {}.", t.since), &t.doc);
    match &t.kind {
        TypeKind::Message { .. } => unreachable!("messages are listed apart"),
        TypeKind::Struct { fields: f } => fields(out, f),
        TypeKind::Union { variants } => {
            out.push_str("| Variant | Carries | Since | |\n|---|---|---|---|\n");
            for v in variants {
                let carries = match &v.payload {
                    Payload::None => "nothing".to_string(),
                    Payload::Fields(_) => "the fields below".to_string(),
                    Payload::Struct(s) => format!("`{s}`"),
                };
                row(
                    out,
                    &[
                        format!("`{}`", v.name),
                        carries,
                        v.since.to_string(),
                        prose(&v.doc),
                    ],
                );
            }
            out.push('\n');
            for v in variants {
                if let Payload::Fields(f) = &v.payload {
                    writeln!(out, "#### `{}.{}`\n", t.name, v.name).unwrap();
                    fields(out, f);
                }
            }
        }
        TypeKind::Enum { values } => {
            out.push_str("| Value | Since | |\n|---|---|---|\n");
            for v in values {
                row(
                    out,
                    &[format!("`{}`", v.name), v.since.to_string(), prose(&v.doc)],
                );
            }
            out.push('\n');
        }
    }
}
