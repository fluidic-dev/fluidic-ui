//! Generates the Go types and their codec. The output is already as gofmt
//! leaves it: struct fields and constants stand apart, so nothing is aligned.

use crate::model::{Field, Payload, Schema, Type, TypeDecl, TypeKind, Variant};
use crate::naming::{MESSAGE_UNIONS, go_case, go_functions, go_name, go_unknown};
use std::collections::BTreeMap;
use std::fmt::Write;

const RUNTIME: &str = include_str!("../runtime/json.go");

const HEADER: &str = "// Code generated by fluidic-ui-idl from the schema. DO NOT EDIT.";

/// The package's `schema.go` and `json.go`.
pub(crate) fn generate(schema: &Schema, package: &str) -> Vec<(String, String)> {
    // The runtime without its note about being copied, which ends at the
    // first blank line after the package clause.
    let body = RUNTIME
        .split_once("package schema\n\n")
        .expect("package clause")
        .1;
    let body = body.split_once("\n\n").expect("the note").1;
    let runtime = format!("{HEADER}\n\npackage {package}\n\n{body}");
    vec![
        ("schema.go".to_string(), file(schema, package)),
        ("json.go".to_string(), runtime),
    ]
}

/// `The app's first message.` becomes `the app's first message.`, but an
/// acronym such as `SDK` keeps its capitals.
fn lower_first(line: &str) -> String {
    let word = line
        .split(|c: char| !c.is_alphanumeric())
        .next()
        .unwrap_or("");
    if word.len() > 1 && word.chars().all(|c| !c.is_lowercase()) {
        return line.to_string();
    }
    let mut chars = line.chars();
    chars.next().map_or_else(String::new, |first| {
        first.to_lowercase().collect::<String>() + chars.as_str()
    })
}

/// A declaration's doc comment, in Go's form: `// Hello is the app's first
/// message.`
fn named_docs(out: &mut String, name: &str, doc: &[String]) {
    if let Some((first, rest)) = doc.split_first() {
        writeln!(out, "// {name} is {}", lower_first(first)).unwrap();
        docs(out, rest, 0);
    }
}

/// Doc comment lines, indented by `indent` tabs.
fn docs(out: &mut String, doc: &[String], indent: usize) {
    for line in doc {
        out.push_str(&"\t".repeat(indent));
        if line.is_empty() {
            out.push_str("//\n");
        } else {
            writeln!(out, "// {line}").unwrap();
        }
    }
}

fn ty(t: &Type) -> String {
    match t {
        Type::Bool => "bool".to_string(),
        Type::U32 => "uint32".to_string(),
        Type::I32 => "int32".to_string(),
        Type::U64 => "uint64".to_string(),
        Type::I64 => "int64".to_string(),
        Type::F32 => "float32".to_string(),
        Type::F64 => "float64".to_string(),
        Type::String => "string".to_string(),
        Type::Version => "Version".to_string(),
        Type::List(t) => format!("[]{}", ty(t)),
        Type::Map(t) => format!("map[string]{}", ty(t)),
        Type::Named(n) => go_name(n),
    }
}

/// The suffix of a type's read and write functions: `readU32`, `writeSDKInfo`,
/// and `readList_U32` for a list. Names from the schema have no underscore,
/// so a list's or map's never collides with them.
fn codec_name(t: &Type) -> String {
    match t {
        Type::Bool => "Bool".to_string(),
        Type::U32 => "U32".to_string(),
        Type::I32 => "I32".to_string(),
        Type::U64 => "U64".to_string(),
        Type::I64 => "I64".to_string(),
        Type::F32 => "F32".to_string(),
        Type::F64 => "F64".to_string(),
        Type::String => "String".to_string(),
        Type::Version => "Version".to_string(),
        Type::Named(n) => go_name(n),
        Type::List(t) => format!("List_{}", codec_name(t)),
        Type::Map(t) => format!("Map_{}", codec_name(t)),
    }
}

/// An expression writing `value` of type `t` to `w`, of type `error`.
fn write_call(t: &Type, value: &str) -> String {
    format!("write{}(w, {value})", codec_name(t))
}

/// An expression reading a value of type `t` from `r`.
fn read_call(t: &Type) -> String {
    format!("read{}(r)", codec_name(t))
}

/// Every list and map type the schema uses, inner ones included.
fn containers(schema: &Schema) -> BTreeMap<String, Type> {
    fn add(t: &Type, found: &mut BTreeMap<String, Type>) {
        if let Type::List(inner) | Type::Map(inner) = t {
            found.insert(codec_name(t), t.clone());
            add(inner, found);
        }
    }
    let mut found = BTreeMap::new();
    for fields in schema.types.iter().flat_map(|t| t.kind.field_lists()) {
        fields.iter().for_each(|f| add(&f.ty, &mut found));
    }
    found
}

/// The read and write functions of a list or map type.
fn container(out: &mut String, t: &Type) {
    let (generic, inner) = match t {
        Type::List(inner) => ("List", inner),
        Type::Map(inner) => ("Map", inner),
        _ => unreachable!("only lists and maps"),
    };
    let (name, inner_name, go_type) = (codec_name(t), codec_name(inner), ty(t));
    writeln!(
        out,
        "func read{name}(r *jsonReader) ({go_type}, error) {{\n\
         \treturn read{generic}(r, read{inner_name})\n}}\n\n\
         func write{name}(w *jsonWriter, v {go_type}) error {{\n\
         \treturn write{generic}(w, v, write{inner_name})\n}}\n"
    )
    .unwrap();
}

/// Whether `t` is a union, which Go holds as a nil-able interface.
fn is_union(schema: &Schema, t: &Type) -> bool {
    match t {
        Type::Named(n) => schema
            .get(n)
            .is_some_and(|d| matches!(d.kind, TypeKind::Union { .. })),
        _ => false,
    }
}

fn file(schema: &Schema, package: &str) -> String {
    let mut out = String::new();
    writeln!(out, "{HEADER}\n\npackage {package}\n").unwrap();
    let c = schema.contract;
    writeln!(
        out,
        "// Contract is the contract version this schema defines.\n\
         var Contract = Version{{Major: {}, Minor: {}}}\n",
        c.major, c.minor
    )
    .unwrap();
    for (sender, name, doc) in MESSAGE_UNIONS {
        let doc = format!("One of {doc}.");
        union(
            &mut out,
            schema,
            name,
            &[doc],
            &schema.message_variants(sender),
        );
        encode_decode(&mut out, name);
    }
    for t in &schema.types {
        declaration(&mut out, schema, t);
    }
    for t in containers(schema).values() {
        container(&mut out, t);
    }
    // Exactly one newline at the end, as gofmt leaves it.
    while out.ends_with("\n\n") {
        out.pop();
    }
    out
}

fn encode_decode(out: &mut String, name: &str) {
    let [encode, decode] = go_functions(name);
    writeln!(
        out,
        "// {encode} returns v's canonical JSON text.\n\
         func {encode}(v {name}) ([]byte, error) {{\n\
         \treturn encodeValue(v, write{name})\n}}\n\n\
         // {decode} reads a {name} from JSON text.\n\
         func {decode}(data []byte) ({name}, error) {{\n\
         \treturn decodeValue(data, read{name})\n}}\n"
    )
    .unwrap();
}

fn declaration(out: &mut String, schema: &Schema, t: &TypeDecl) {
    let name = go_name(&t.name);
    match &t.kind {
        TypeKind::Message { fields, .. } | TypeKind::Struct { fields } => {
            structure(out, schema, &name, &t.doc, fields);
            encode_decode(out, &name);
        }
        TypeKind::Union { variants } => {
            union(out, schema, &name, &t.doc, variants);
            encode_decode(out, &name);
        }
        TypeKind::Enum { values } => {
            named_docs(out, &name, &t.doc);
            writeln!(out, "type {name} string\n").unwrap();
            for v in values {
                let constant = go_case(&name, &v.name);
                named_docs(out, &constant, &v.doc);
                writeln!(out, "const {constant} {name} = \"{}\"\n", v.name).unwrap();
            }
            writeln!(out, "// Known reports whether v is a value this side knows.\nfunc (v {name}) Known() bool {{").unwrap();
            let cases: Vec<String> = values.iter().map(|v| go_case(&name, &v.name)).collect();
            writeln!(
                out,
                "\tswitch v {{\n\tcase {}:\n\t\treturn true\n\t}}",
                cases.join(", ")
            )
            .unwrap();
            out.push_str("\treturn false\n}\n\n");
            writeln!(
                out,
                "func write{name}(w *jsonWriter, v {name}) error {{\n\
                 \tif !v.Known() {{\n\t\treturn encodeUnknown(string(v))\n\t}}\n\
                 \tw.string(string(v))\n\treturn nil\n}}\n\n\
                 func read{name}(r *jsonReader) ({name}, error) {{\n\
                 \ts, err := readString(r)\n\treturn {name}(s), err\n}}\n"
            )
            .unwrap();
            encode_decode(out, &name);
        }
    }
}

/// A struct with its read and write functions.
fn structure(out: &mut String, schema: &Schema, name: &str, doc: &[String], fields: &[Field]) {
    named_docs(out, name, doc);
    if fields.is_empty() {
        writeln!(out, "type {name} struct{{}}\n").unwrap();
    } else {
        writeln!(out, "type {name} struct {{").unwrap();
        for (i, f) in fields.iter().enumerate() {
            if i > 0 {
                out.push('\n');
            }
            docs(out, &f.doc, 1);
            let pointer = if f.optional && !is_union(schema, &f.ty) {
                "*"
            } else {
                ""
            };
            writeln!(out, "\t{} {pointer}{}", go_name(&f.name), ty(&f.ty)).unwrap();
        }
        out.push_str("}\n\n");
    }

    writeln!(
        out,
        "func write{name}(w *jsonWriter, v {name}) error {{\n\tw.beginObject()"
    )
    .unwrap();
    for f in fields {
        let field = format!("v.{}", go_name(&f.name));
        if f.optional {
            let value = if is_union(schema, &f.ty) {
                field.clone()
            } else {
                format!("*{field}")
            };
            writeln!(
                out,
                "\tif {field} != nil {{\n\t\tw.key(\"{}\")\n\t\tif err := {}; err != nil {{\n\t\t\treturn err\n\t\t}}\n\t}}",
                f.name,
                write_call(&f.ty, &value)
            )
            .unwrap();
        } else {
            writeln!(
                out,
                "\tw.key(\"{}\")\n\tif err := {}; err != nil {{\n\t\treturn err\n\t}}",
                f.name,
                write_call(&f.ty, &field)
            )
            .unwrap();
        }
    }
    out.push_str("\tw.endObject()\n\treturn nil\n}\n\n");

    let required: Vec<&Field> = fields.iter().filter(|f| !f.optional).collect();
    writeln!(
        out,
        "func read{name}(r *jsonReader) ({name}, error) {{\n\tvar v {name}"
    )
    .unwrap();
    if !required.is_empty() {
        writeln!(out, "\tvar seen [{}]bool", required.len()).unwrap();
    }
    out.push_str(
        "\tobject, err := r.object()\n\tif err != nil {\n\t\treturn v, err\n\t}\n\
         \tfor {\n\t\tkey, ok, err := object.next(r)\n\t\tif err != nil {\n\t\t\treturn v, err\n\t\t}\n\
         \t\tif !ok {\n\t\t\tbreak\n\t\t}\n",
    );
    if fields.is_empty() {
        out.push_str(
            "\t\t_ = key\n\t\tif err := r.skip(); err != nil {\n\t\t\treturn v, err\n\t\t}\n",
        );
    } else {
        out.push_str("\t\tswitch key {\n");
        for f in fields {
            writeln!(out, "\t\tcase \"{}\":", f.name).unwrap();
            let field = format!("v.{}", go_name(&f.name));
            if f.optional && !is_union(schema, &f.ty) {
                writeln!(
                    out,
                    "\t\t\t{field}, err = readOptional(r, read{})",
                    codec_name(&f.ty)
                )
                .unwrap();
            } else {
                writeln!(out, "\t\t\t{field}, err = {}", read_call(&f.ty)).unwrap();
            }
            if let Some(i) = required.iter().position(|r| r.name == f.name) {
                writeln!(out, "\t\t\tseen[{i}] = true").unwrap();
            }
        }
        out.push_str("\t\tdefault:\n\t\t\terr = r.skip()\n\t\t}\n\t\tif err != nil {\n\t\t\treturn v, err\n\t\t}\n");
    }
    out.push_str("\t}\n");
    for (i, f) in required.iter().enumerate() {
        writeln!(
            out,
            "\tif !seen[{i}] {{\n\t\treturn v, r.missing(\"{}\")\n\t}}",
            f.name
        )
        .unwrap();
    }
    out.push_str("\treturn v, nil\n}\n\n");
}

/// The Go type that holds a variant: its own struct, or the struct it carries.
fn variant_type(union: &str, v: &Variant) -> String {
    match &v.payload {
        Payload::Struct(s) => go_name(s),
        _ => go_case(union, &v.name),
    }
}

fn union(out: &mut String, schema: &Schema, name: &str, doc: &[String], variants: &[Variant]) {
    let marker = format!("is{name}");
    let unknown = go_unknown(name);
    named_docs(out, name, doc);
    writeln!(out, "type {name} interface {{\n\t{marker}()\n}}\n").unwrap();
    for v in variants {
        let held = variant_type(name, v);
        match &v.payload {
            Payload::None => {
                named_docs(out, &held, &v.doc);
                writeln!(out, "type {held} struct{{}}\n").unwrap();
            }
            Payload::Fields(fields) => structure(out, schema, &held, &v.doc, fields),
            Payload::Struct(_) => {}
        }
        writeln!(out, "func ({held}) {marker}() {{}}\n").unwrap();
    }
    writeln!(
        out,
        "// {unknown} is a variant this side does not know, by name.\n\
         type {unknown} struct {{\n\tName string\n}}\n\n\
         func ({unknown}) {marker}() {{}}\n"
    )
    .unwrap();

    writeln!(
        out,
        "func write{name}(w *jsonWriter, v {name}) error {{\n\tswitch v := v.(type) {{"
    )
    .unwrap();
    for v in variants {
        let held = variant_type(name, v);
        writeln!(out, "\tcase {held}:").unwrap();
        if v.payload == Payload::None {
            writeln!(out, "\t\tw.string(\"{}\")\n\t\treturn nil", v.name).unwrap();
        } else {
            writeln!(
                out,
                "\t\tw.beginObject()\n\t\tw.key(\"{}\")\n\t\tif err := write{held}(w, v); err != nil {{\n\t\t\treturn err\n\t\t}}\n\t\tw.endObject()\n\t\treturn nil",
                v.name
            )
            .unwrap();
        }
    }
    writeln!(
        out,
        "\tcase {unknown}:\n\t\treturn encodeUnknown(v.Name)\n\tcase nil:\n\t\treturn encodeUnset(\"{name}\")\n\t}}\n\
         \treturn encodeNotVariant(v, \"{name}\")\n}}\n"
    )
    .unwrap();

    let bare: Vec<&Variant> = variants
        .iter()
        .filter(|v| v.payload == Payload::None)
        .collect();
    let data: Vec<&Variant> = variants
        .iter()
        .filter(|v| v.payload != Payload::None)
        .collect();
    let names = |vs: &[&Variant]| {
        vs.iter()
            .map(|v| format!("\"{}\"", v.name))
            .collect::<Vec<_>>()
            .join(", ")
    };
    writeln!(
        out,
        "func read{name}(r *jsonReader) ({name}, error) {{\n\
         \tname, data, err := r.tag()\n\tif err != nil {{\n\t\treturn nil, err\n\t}}\n\tif !data {{"
    )
    .unwrap();
    if !variants.is_empty() {
        out.push_str("\t\tswitch name {\n");
        for v in &bare {
            writeln!(
                out,
                "\t\tcase \"{}\":\n\t\t\treturn {}{{}}, nil",
                v.name,
                variant_type(name, v)
            )
            .unwrap();
        }
        if !data.is_empty() {
            writeln!(
                out,
                "\t\tcase {}:\n\t\t\treturn nil, r.bareWithData(name)",
                names(&data)
            )
            .unwrap();
        }
        out.push_str("\t\t}\n");
    }
    writeln!(
        out,
        "\t\treturn {unknown}{{Name: name}}, nil\n\t}}\n\tvar v {name}"
    )
    .unwrap();
    if variants.is_empty() {
        writeln!(out, "\tv, err = {unknown}{{Name: name}}, r.skip()").unwrap();
    } else {
        out.push_str("\tswitch name {\n");
        if !bare.is_empty() {
            writeln!(
                out,
                "\tcase {}:\n\t\treturn nil, r.dataWithoutData(name)",
                names(&bare)
            )
            .unwrap();
        }
        for v in &data {
            writeln!(
                out,
                "\tcase \"{}\":\n\t\tv, err = read{}(r)",
                v.name,
                variant_type(name, v)
            )
            .unwrap();
        }
        writeln!(
            out,
            "\tdefault:\n\t\tv, err = {unknown}{{Name: name}}, r.skip()\n\t}}"
        )
        .unwrap();
    }
    out.push_str("\tif err != nil {\n\t\treturn nil, err\n\t}\n\treturn v, r.endTag()\n}\n\n");
}
